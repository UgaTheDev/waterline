const DICT: Record<Lang, Record<Key, string>> = { en, es };

export function translate(lang: Lang, key: Key, vars?: Vars) {
  const s = DICT[lang][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
export type T = (key: Key, vars?: Vars) => string;

// The choice is a per-viewer convenience: stored in localStorage, else the browser language, and storage failures are ignored.
const KEY = "waterline-lang";
let memo: Lang | null = null;
const listeners = new Set<() => void>();

function read(): Lang {
  if (memo) return memo;
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(KEY);
  } catch {}
  memo = saved === "es" || saved === "en" ? saved : navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
  return memo;
}

export const currentLang = (): Lang => (typeof window === "undefined" ? "en" : read());

export function setLang(l: Lang) {
  memo = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {}
  listeners.forEach((f) => f());
}

// The server always renders English; the client switches after hydration.
export const useLang = () =>
  useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => listeners.delete(l);
    },
    read,
    () => "en" as Lang,
  );

export function useT(): T {
  const lang = useLang();
  return useCallback((key: Key, vars?: Vars) => translate(lang, key, vars), [lang]);
}

// Vehicle names by id; the /config label is the English fallback. English keeps its old casing rules exactly.
export function vehicleName(t: T, lang: Lang, v: { id: string; label: string }, lower = false) {
  if (lang === "en") return lower ? v.label.toLowerCase() : v.label;
  const k = `veh.${v.id}` as Key;
  const n = k in en ? t(k) : v.label;
  return lower ? lowerName(lang, n) : n;
}
// Mid-sentence form: Spanish keeps acronyms ("SUV") as they are.
export const lowerName = (lang: Lang, n: string) => (lang === "es" && n === n.toUpperCase() ? n : n.toLowerCase());

// The router's English strings (backend/router.py), rebuilt in Spanish; anything unrecognised is shown as sent.
export function routerText(lang: Lang, s: string) {
  if (lang === "en" || !s) return s;
  let m = s.match(/^reported up to (\d+) cm; .+ limit (\d+) cm$/);
  if (m) return `reportado hasta ${m[1]} cm; el límite de su vehículo es ${m[2]} cm`;
  if (s === "water reported, depth unreadable") return "agua reportada, profundidad ilegible";
  if (/^No route avoids reported deep water for a .+\.$/.test(s)) return "Ninguna ruta evita el agua profunda reportada para su vehículo.";
  m = s.match(/^Route passes (\d+) m of streets with no recent reports inside an active flood warning\.$/);
  if (m) return `La ruta pasa por ${m[1]} m de calles sin reportes recientes dentro de un aviso de inundación activo.`;
  return s;
}
