"""Stream D (Cosmos Transfer simulations). CONTRACT, frozen 2026-09-27: GET /simulations -> [{id, street, depth_cm,
video_url, label}] read from data/cache/simulations.json. Every clip has the SIMULATION label burned in; simulations are
never evidence and never touch /segments or routing."""
import json
from fastapi import APIRouter
from . import events
from .profiles import CACHE

router = APIRouter()
LABEL = "SIMULATION: generated by NVIDIA Cosmos Transfer, not a real photo"


@router.get("/simulations")
def simulations(event: str | None = None):
    if events.get(event)["id"] != events.DEFAULT:
        return []  # the clips are generated from Harvey streets
    p = CACHE / "simulations.json"
    return [dict(s, label=LABEL) for s in json.loads(p.read_text())] if p.exists() else []
